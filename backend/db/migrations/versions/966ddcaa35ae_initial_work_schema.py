def _enable_rls() -> None:
    for table in _TENANT_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} FORCE  ROW LEVEL SECURITY")
        op.execute(
            f"CREATE POLICY {table}_org_isolation ON {table} "
            f"USING (org_id = {_ORG}) WITH CHECK (org_id = {_ORG})"
        )

    # membership carries a SECOND policy, and it is not an exception grudgingly
    # made. Postgres ORs permissive policies, so this adds "my own rows" to "rows
    # in the current org". Without it the login bootstrap is impossible: a user
    # who has just authenticated has no organization yet, so a policy keyed only
    # on org_id would hide the very rows that say which organizations they may
    # enter, and every user would be locked out.
    op.execute(
        "CREATE POLICY membership_self ON membership "
        f"USING (user_id = {_USR}) WITH CHECK (user_id = {_USR})"
    )


def _disable_rls() -> None:
    op.execute("DROP POLICY IF EXISTS membership_self ON membership")
    for table in _TENANT_TABLES:
        op.execute(f"DROP POLICY IF EXISTS {table}_org_isolation ON {table}")
        op.execute(f"ALTER TABLE {table} NO FORCE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} DISABLE ROW LEVEL SECURITY")


