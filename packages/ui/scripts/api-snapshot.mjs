/* =============================================================================
   api-snapshot.mjs — record the kit's PUBLIC export surface, so a breaking
   change cannot ship without someone noticing.

     node scripts/api-snapshot.mjs           rewrite api/ui.api.md
     node scripts/api-snapshot.mjs --check   exit 1 if it drifted from the file

   Why this exists: `Menu` changed from an `items` prop to `MenuItem` children
   with no version bump. Out-of-repo consumers resolved the kit as source
   through a path alias, so nothing compiled them and nothing failed. The
   version pin said `^1` throughout. This file makes that class of change a
   visible diff in a reviewed artifact.

   Scope: the snapshot covers the export NAMES of each public entry point. It is
   deliberately not a full type report (that would need api-extractor, which is
   not vendored here) — a removed or renamed export is the failure mode that
   actually bit, and this catches it. Prop-level changes still need the
   CHANGELOG, which is why the version bump rule in CONTRIBUTING points at both.
   ========================================================================== */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const SNAPSHOT = resolve(ROOT, "api/ui.api.md");

const pkg = JSON.parse(readFileSync(resolve(ROOT, "package.json"), "utf8"));

// The entry points, read off the exports map so the snapshot can never cover a
// different set of subpaths than the package actually publishes.
const ENTRIES = Object.entries(pkg.exports)
  .filter(([, target]) => typeof target === "object" && target["workshop-source"])
  .map(([subpath, target]) => ({
    subpath: subpath === "." ? "@workshop/ui" : `@workshop/ui${subpath.slice(1)}`,
    file: resolve(ROOT, target["workshop-source"]),
  }))
  .filter(({ file }) => /\.(ts|tsx)$/.test(file));

/* Collect the export names from one module, following `export ... from "./x"`
   re-exports so the barrel file reports the real surface rather than a list of
   filenames. */
function exportsOf(file, seen = new Set()) {
  if (seen.has(file) || !existsSync(file)) return [];
  seen.add(file);
  const src = readFileSync(file, "utf8");
  const names = [];

  // export { a, b as c, type D } from "./mod"   |   export { a, b }
  const braced = /export\s*\{([^}]*)\}\s*(?:from\s*["']([^"']+)["'])?/g;
  for (const m of src.matchAll(braced)) {
    for (const raw of m[1].split(",")) {
      const part = raw.trim();
      if (!part) continue;
      const isType = part.startsWith("type ");
      const body = isType ? part.slice(5).trim() : part;
      const name = (body.split(/\s+as\s+/)[1] ?? body).trim();
      if (name) names.push(isType ? `type ${name}` : name);
    }
  }

  // export function f / const c / class C / type T / interface I
  const direct = /export\s+(?:declare\s+)?(function|const|let|class|type|interface)\s+([A-Za-z0-9_$]+)/g;
  for (const m of src.matchAll(direct)) {
    names.push(m[1] === "type" || m[1] === "interface" ? `type ${m[2]}` : m[2]);
  }

  // export * from "./mod" — follow it, the names live downstream.
  const star = /export\s+\*\s+from\s*["']([^"']+)["']/g;
  for (const m of src.matchAll(star)) {
    names.push(...exportsOf(resolveRel(file, m[1]), seen));
  }

  return names;
}

function resolveRel(from, spec) {
  const base = resolve(dirname(from), spec);
  for (const ext of ["", ".ts", ".tsx", "/index.ts", "/index.tsx"]) {
    if (existsSync(base + ext)) return base + ext;
  }
  return base;
}

const lines = [
  "# @workshop/ui — public API",
  "",
  "GENERATED by `npm run api:snapshot`. Do not edit by hand.",
  "",
  "This is the contract other apps compile against. A name leaving this file, or",
  "changing shape, is a BREAKING change and needs a major version bump plus a",
  "CHANGELOG migration note. See CONTRIBUTING.md.",
  "",
  `Version: ${pkg.version}`,
  "",
];

for (const { subpath, file } of ENTRIES) {
  const names = [...new Set(exportsOf(file))].sort((a, b) => a.localeCompare(b));
  lines.push(`## ${subpath}`, "", `Source: \`${relative(ROOT, file)}\``, "");
  for (const n of names) lines.push(`- ${n}`);
  lines.push("");
}

// The non-code entry points are part of the contract too: a consumer importing
// @workshop/ui/tokens.css breaks just as hard if that subpath disappears.
const assets = Object.keys(pkg.exports).filter((s) => /\.(css|js)$/.test(s));
if (assets.length) {
  lines.push("## Asset entry points", "");
  for (const a of assets.sort()) lines.push(`- @workshop/ui${a.slice(1)}`);
  lines.push("");
}

const next = lines.join("\n");
const check = process.argv.includes("--check");

if (!check) {
  writeFileSync(SNAPSHOT, next);
  console.log(`api-snapshot: wrote ${relative(ROOT, SNAPSHOT)}`);
  process.exit(0);
}

const current = existsSync(SNAPSHOT) ? readFileSync(SNAPSHOT, "utf8") : "";
if (current === next) {
  console.log(`api-snapshot: public API matches ${relative(ROOT, SNAPSHOT)} (v${pkg.version})`);
  process.exit(0);
}

console.error(
  "api-snapshot: the public API of @workshop/ui changed but api/ui.api.md was not updated.\n" +
    "  If this is intentional: bump the version in packages/ui/package.json, add a\n" +
    "  CHANGELOG.md entry (a REMOVED or RENAMED export means a MAJOR bump), then run\n" +
    "  `npm run api:snapshot --workspace @workshop/ui` and commit the result."
);

// Show the actual drift; a bare "it differs" sends the reader hunting.
const a = current.split("\n");
const b = next.split("\n");
const removed = a.filter((l) => l.startsWith("- ") && !b.includes(l));
const added = b.filter((l) => l.startsWith("- ") && !a.includes(l));
for (const l of removed) console.error(`  REMOVED ${l.slice(2)}`);
for (const l of added) console.error(`  ADDED   ${l.slice(2)}`);
process.exit(1);
