import AppKit
import ServiceManagement

/// The system clipboard, for the web UI (shared/native-bridge.ts `clipboard`).
/// `write` needs no user gesture, which the page's own clipboard does. With the
/// watch on "everything", each copy made in another app is reported to the
/// backend here (`CopyReporter`), page open or not, and Workshop opens at
/// login; copies made while Workshop is in front are left to the page, which
/// reports its own.
@MainActor
final class ClipboardBridge {
    static let modeKey = "clipboardWatch"
    static let modes = ["workshop", "everything"]
    /// Markers an app sets on an item it does not want kept (nspasteboard.org).
    static let skipped: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        own,
    ]
    /// On every item Workshop itself puts on the clipboard.
    static let own = NSPasteboard.PasteboardType("home.workshop.own")

    /// Told the mode at launch and each time it is set.
    var onMode: ((String) -> Void)? {
        didSet { onMode?(Self.mode) }
    }
    private let board = NSPasteboard.general
    private let reporter: CopyReporter
    private var seen: Int
    private var timer: Timer?

    init(reporter: CopyReporter) {
        self.reporter = reporter
        seen = NSPasteboard.general.changeCount
        apply(Self.mode)
    }

    static var mode: String {
        let stored = UserDefaults.standard.string(forKey: modeKey) ?? ""
        return modes.contains(stored) ? stored : "workshop"
    }

    func install(on bridge: Bridge) {
        bridge.handle("clipboard", "write") { [weak self] args, _ in
            guard let text = args.first as? String else { throw ClipboardError.notText }
            return self?.write(text) ?? false
        }
        bridge.handle("clipboard", "watch.get") { _, _ in Self.mode }
        bridge.handle("clipboard", "watch.set") { [weak self] args, _ in
            guard let mode = args.first as? String, Self.modes.contains(mode) else {
                throw ClipboardError.badMode
            }
            UserDefaults.standard.set(mode, forKey: Self.modeKey)
            self?.apply(mode)
            Self.openAtLogin(mode == "everything")
            self?.onMode?(mode)
            return mode
        }
    }

    func write(_ text: String) -> Bool {
        board.declareTypes([.string, Self.own], owner: nil)
        let done = board.setString(text, forType: .string) && board.setData(Data(), forType: Self.own)
        seen = board.changeCount
        return done
    }

    /// Watching everything means running from login on; set back, it stops.
    private static func openAtLogin(_ on: Bool) {
        let item = SMAppService.mainApp
        do {
            if on, item.status != .enabled {
                try item.register()
            } else if !on, item.status == .enabled || item.status == .requiresApproval {
                try item.unregister()
            }
        } catch {
            NSLog("Workshop: open at login %@: %@", on ? "on" : "off", "\(error)")
        }
    }

    private func apply(_ mode: String) {
        timer?.invalidate()
        timer = nil
        seen = board.changeCount
        guard mode == "everything" else { return }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let count = board.changeCount
        guard count != seen else { return }
        seen = count
        let front = NSWorkspace.shared.frontmostApplication
        if front?.processIdentifier == ProcessInfo.processInfo.processIdentifier { return }
        let types = Set(board.types ?? [])
        guard types.isDisjoint(with: Self.skipped),
              let text = board.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }
        reporter.report(text, app: front?.localizedName ?? "")
    }
}

enum ClipboardError: LocalizedError {
    case notText, badMode

    var errorDescription: String? {
        switch self {
        case .notText: return "clipboard.write takes a string"
        case .badMode: return "clipboard.watch.set takes \"workshop\" or \"everything\""
        }
    }
}
