#!/usr/bin/env python3
"""One implementation per helper, ratcheted. The level below
`check_one_definition.py`: that one catches the same VALUE SET declared twice,
this one catches the same FUNCTION BODY declared twice.

THE FINDING THIS PROTECTS. Measured 2026-08-17 in `frontend/src`, tests
excluded: `fmtTs` declared three times (byte-identical apart from one
`| null`), `short(sha)` three times, `specColor` twice with a comment in the
second copy reading "Same palette as the recorder's" -- a stated invariant
that nothing enforced. The damning part is not that nobody had written the
shared version: `lib/time.ts` already exported `timeAbsolute`, which IS
`fmtTs`, and its own header already documents that sixteen copies of this
exact family had been consolidated once before. So the failure mode is not
"no canonical home", it is "the canonical home exists and the next page
rewrote the helper anyway", which no name-based grep and no enum checker can
see.

WHAT THIS COUNTS. Function declarations in `frontend/src` and
`packages/ui/src`:

    function name(...) { ... }          (incl. export / async / generic)
    const name = (...) => { ... }
    const name = (...) => expr;

Their BODY is normalised (comments stripped, all whitespace collapsed) and
hashed. Two or more declarations in DIFFERENT FILES with the same hash are a
duplicate group.

The signature is deliberately NOT part of the comparison. That is what makes
`fmtTs(ts?: string)` and `fmtTs(ts?: string | null)` one function here, which
is what they are: the annotation is the only thing that differed across the
three copies, and comparing signatures would have hidden the group behind it.
Plain parameter names ARE rewritten positionally in the body (`_p0`, `_p1`),
so a copy that renamed its argument still matches; two bodies that differ only
in what an argument is called are one function by definition. Destructured
parameters are left alone, because there the name is also a property name.

WHAT IT STILL MISSES, AND THIS IS THE IMPORTANT LIMIT. It compares bodies
literally, so it catches COPY-PASTE, not independent reimplementation.
`fmtTs`'s three copies were caught because they were the same characters; none
of them would have matched `lib/time.ts`'s `timeAbsolute`, which is the same
function written once with `Number.isNaN` instead of `isNaN`. Nothing
mechanical finds that. A reviewer looking for a home for a new helper still
has to look.

WHAT IS EXCLUDED, AND WHY EACH ONE.

  * `frontend/src/api/schema.gen.ts` and anything else matching `*.gen.ts` /
    `*.generated.*` -- generated artifacts. schema.gen.ts alone is ~22k lines
    regenerated by `npm run gen:api-types`; a duplicate inside it is a fact
    about the backend's schema, not a thing a person can consolidate.
  * `*.test.ts(x)`, `*.spec.*`, `__tests__/` -- a test legitimately re-states
    a fixture or a tiny helper next to the assertions that use it, and the
    drift this exists to catch is two PRODUCTION modules disagreeing.
  * `node_modules`, `dist`, `build`, `coverage`, `scratch`, `tmp`,
    `standalone`, `.venv` -- vendored, built, or throwaway.
  * Bodies shorter than `_MIN_BODY_CHARS` normalised characters. `return
    x.trim()`, `return this.props.value`, `setOpen(false)` and every other
    one-line pass-through collide constantly and consolidating them would
    make the code worse, not better. The threshold is set just below the
    real `short(sha)` group (27 chars normalised), which IS worth
    consolidating because it is three copies of a decision (7 characters, and
    "" for a missing sha) rather than three copies of a language construct.
  * Bodies made only of `return`/`throw` of a single call with no operators
    (`_is_trivial`), regardless of length, for the same reason.

WHY A BASELINE, NOT AN ABSOLUTE GATE. There are pre-existing duplicate groups
this run cannot touch (the chat subsystem is being renamed by another agent as
this lands, so `useNow` and `firstLine` are deliberately left alone). Failing
on all of them would fail the reviewer for every unrelated task in the repo,
which is "a checker that fires constantly gets disabled, which is how we got
here" (`check_one_definition.py`'s own header, and the reason this file
exists). So `duplicate_helpers_baseline.json` pins today's groups by body
hash together with the NUMBER of files each is declared in, exactly the shape
`check_response_model.py` pins per-file counts in, and this fails on:

    * a body hash not in the baseline at all  -- a NEW duplicated helper
    * a baselined hash now declared in MORE files -- a copy was added to an
      existing duplicate

and never on a group that has stayed put or shrunk. Hashing the BODY rather
than the file list is what makes the baseline survive the rename in flight:
moving a copy from one file to another is not a regression, adding a fourth
copy is. `--only-changed <rev>` narrows FAILURE further, to groups where at
least one declaring file is in the diff, the same gate mode
`check_one_definition.py` and `check_response_model.py` use. Every group is
PRINTED either way, so the debt stays visible.

Usage:
    python3 scripts/check_duplicate_helpers.py                  # report + exit 1 on regression
    python3 scripts/check_duplicate_helpers.py --json
    python3 scripts/check_duplicate_helpers.py --all            # print every group, baselined or not
    python3 scripts/check_duplicate_helpers.py --only-changed HEAD
    python3 scripts/check_duplicate_helpers.py --write-baseline
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

_WORKSHOP = Path(__file__).resolve().parents[1]
_BASELINE_PATH = Path(__file__).resolve().parent / "duplicate_helpers_baseline.json"

_ROOTS = [_WORKSHOP / "frontend" / "src", _WORKSHOP / "packages" / "ui" / "src"]
_SUFFIXES = (".ts", ".tsx")

_EXCLUDE_DIR_PARTS = {
    "node_modules", ".venv", "__pycache__", "dist", "build", ".git",
    "coverage", ".next", "scratch", "tmp", "__tests__", "standalone",
}
_EXCLUDE_FILE_RE = re.compile(r"(\.test\.|\.spec\.|\.gen\.|\.generated\.|\.d\.ts$)")

# Below this many characters of normalised body, a collision is a language
# construct rather than a shared decision. `short(sha)` normalises to 27.
_MIN_BODY_CHARS = 25


# --------------------------------------------------------------------------
# A very small TypeScript lexer. Enough to know what is code and what is a
# string, a template, a regex or a comment -- which is all that brace matching
# and declaration finding need, and all that keeps a `//` inside a URL string
# from blanking the rest of a line.
# --------------------------------------------------------------------------

_REGEX_PRECEDERS = set("(,=:[!&|?{};+-*%~^<>") | {"\n"}


def _lex(src: str) -> tuple[str, str]:
    """Return (code_mask, no_comments), both the same length as `src`.

    `code_mask` blanks every character inside a string, template, regex or
    comment, so structural scanning sees only code. `no_comments` blanks only
    comments, so string CONTENT still takes part in the body comparison (two
    helpers differing only in a literal are two helpers).
    """
    mask = list(src)
    nocom = list(src)
    i, n = 0, len(src)
    # Template-literal nesting: each entry is the brace depth at which the
    # current `${ ... }` interpolation started.
    tmpl_stack: list[int] = []
    depth = 0
    prev_sig = "\n"  # last significant code character seen

    def blank(a: int, b: int, in_mask=True, in_nocom=False) -> None:
        for k in range(a, b):
            if src[k] != "\n":
                if in_mask:
                    mask[k] = " "
                if in_nocom:
                    nocom[k] = " "

    while i < n:
        c = src[i]
        nxt = src[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = src.find("\n", i)
            j = n if j < 0 else j
            blank(i, j, in_mask=True, in_nocom=True)
            i = j
            continue
        if c == "/" and nxt == "*":
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            blank(i, j, in_mask=True, in_nocom=True)
            i = j
            continue
        if c in "'\"":
            j = i + 1
            while j < n:
                if src[j] == "\\":
                    j += 2
                    continue
                if src[j] == c or src[j] == "\n":
                    break
                j += 1
            blank(i + 1, min(j, n))
            i = min(j + 1, n)
            prev_sig = "'"
            continue
        if c == "`":
            tmpl_stack.append(depth)
            j = i + 1
            while j < n:
                if src[j] == "\\":
                    blank(j, j + 2)
                    j += 2
                    continue
                if src[j] == "`":
                    break
                if src[j] == "$" and j + 1 < n and src[j + 1] == "{":
                    break
                if src[j] != "\n":
                    mask[j] = " "
                j += 1
            if j < n and src[j] == "`":
                tmpl_stack.pop()
                i = j + 1
                prev_sig = "`"
                continue
            if j < n:  # hit `${`: fall back into code mode, tracking the brace
                depth += 1
                i = j + 2
                prev_sig = "{"
                continue
            i = n
            continue
        if c == "/" and prev_sig in _REGEX_PRECEDERS:
            j = i + 1
            in_class = False
            ok = False
            while j < n:
                d = src[j]
                if d == "\\":
                    j += 2
                    continue
                if d == "\n":
                    break
                if d == "[":
                    in_class = True
                elif d == "]":
                    in_class = False
                elif d == "/" and not in_class:
                    ok = True
                    break
                j += 1
            if ok:
                blank(i + 1, j)
                i = j + 1
                prev_sig = "/"
                continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if tmpl_stack and depth == tmpl_stack[-1]:
                # closing a `${ ... }`: resume template-literal scanning
                j = i + 1
                while j < n:
                    if src[j] == "\\":
                        blank(j, j + 2)
                        j += 2
                        continue
                    if src[j] == "`":
                        tmpl_stack.pop()
                        break
                    if src[j] == "$" and j + 1 < n and src[j + 1] == "{":
                        break
                    if src[j] != "\n":
                        mask[j] = " "
                    j += 1
                if j < n and src[j] == "`":
                    i = j + 1
                    prev_sig = "`"
                    continue
                if j < n:
                    depth += 1
                    i = j + 2
                    prev_sig = "{"
                    continue
                i = n
                continue
        if not c.isspace():
            prev_sig = c
        i += 1
    return "".join(mask), "".join(nocom)


def _match_pair(code: str, start: int, open_ch: str, close_ch: str) -> int:
    """Index just past the `close_ch` matching the `open_ch` at `start`, or -1."""
    depth = 0
    for i in range(start, len(code)):
        if code[i] == open_ch:
            depth += 1
        elif code[i] == close_ch:
            depth -= 1
            if depth == 0:
                return i + 1
    return -1


_FUNC_RE = re.compile(
    r"(?:^|\n)[ \t]*(?:export\s+)?(?:default\s+)?(?:async\s+)?function\s*\*?\s*"
    r"([A-Za-z_$][\w$]*)\s*(?:<[^<>()]*>\s*)?\("
)
_ARROW_RE = re.compile(
    r"(?:^|\n)[ \t]*(?:export\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*"
    r"(?::[^=\n]+?)?=\s*(?:async\s+)?(?:<[^<>()]*>\s*)?\("
)


@dataclass
class Decl:
    name: str
    file: str  # repo-relative
    line: int
    body: str  # normalised
    digest: str


_PARAM_NAME_RE = re.compile(r"^\s*(?:readonly\s+|\.\.\.)?([A-Za-z_$][\w$]*)\s*(?:[?:=,)]|$)")


def _param_names(sig: str) -> list[str]:
    """The plain parameter identifiers of a signature (the text between the
    parentheses), in order. A destructured or otherwise non-identifier
    parameter yields nothing: inside `({ a, b })` the name is also a property
    name, and rewriting it would change what the body says."""
    parts, depth, cur = [], 0, []
    for ch in sig:
        if ch in "([{<":
            depth += 1
        elif ch in ")]}>":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur))
    out = []
    for p in parts:
        if not p.strip():
            continue
        m = _PARAM_NAME_RE.match(p)
        out.append(m.group(1) if m else "")
    return out


def _normalise(body: str, params: list[str]) -> str:
    norm = re.sub(r"\s+", " ", body).strip()
    for i, p in enumerate(params):
        if not p:
            continue
        norm = re.sub(rf"(?<![\w$.]){re.escape(p)}(?![\w$])", f"_p{i}", norm)
    return norm


_TRIVIAL_RE = re.compile(r"^\{?\s*(?:return\s+)?[\w$.]+\([^()]*\)\s*;?\s*\}?$")


def _is_trivial(norm: str) -> bool:
    """A body that is one call and nothing else. `fetchThing(id)`,
    `return props.onClose()`. Two of these matching says the language has one
    way to call a function, not that a helper was duplicated."""
    return bool(_TRIVIAL_RE.match(norm))


def _extract(code: str, nocom: str, rel: str) -> list[Decl]:
    out: list[Decl] = []
    for rx, is_arrow in ((_FUNC_RE, False), (_ARROW_RE, True)):
        for m in rx.finditer(code):
            name = m.group(1)
            paren = code.rfind("(", m.start(), m.end())
            after = _match_pair(code, paren, "(", ")")
            if after < 0:
                continue
            params = _param_names(nocom[paren + 1:after - 1])
            if is_arrow:
                arrow = code.find("=>", after)
                if arrow < 0 or arrow > after + 200:
                    continue
                j = arrow + 2
                while j < len(code) and code[j].isspace():
                    j += 1
                if j >= len(code):
                    continue
                if code[j] == "{":
                    end = _match_pair(code, j, "{", "}")
                    if end < 0:
                        continue
                    body = nocom[j + 1:end - 1]
                else:  # expression body: to the first `;` at depth zero
                    depth = 0
                    k = j
                    while k < len(code):
                        ch = code[k]
                        if ch in "([{":
                            depth += 1
                        elif ch in ")]}":
                            if depth == 0:
                                break
                            depth -= 1
                        elif ch == ";" and depth == 0:
                            break
                        k += 1
                    body = nocom[j:k]
            else:
                j = code.find("{", after)
                if j < 0:
                    continue
                end = _match_pair(code, j, "{", "}")
                if end < 0:
                    continue
                body = nocom[j + 1:end - 1]
            norm = _normalise(body, params)
            if len(norm) < _MIN_BODY_CHARS or _is_trivial(norm):
                continue
            line = code.count("\n", 0, m.start()) + (2 if m.start() else 1)
            out.append(Decl(name, rel, line, norm,
                            hashlib.sha1(norm.encode()).hexdigest()[:12]))
    return out


def _iter_files() -> list[Path]:
    out = []
    for root in _ROOTS:
        if not root.is_dir():
            continue
        for p in sorted(root.rglob("*")):
            if not p.is_file() or p.suffix not in _SUFFIXES:
                continue
            rel_parts = p.relative_to(_WORKSHOP).parts
            if any(part in _EXCLUDE_DIR_PARTS for part in rel_parts):
                continue
            if _EXCLUDE_FILE_RE.search(p.name):
                continue
            out.append(p)
    return out


@dataclass
class Group:
    digest: str
    decls: list[Decl]

    @property
    def files(self) -> list[str]:
        return sorted({d.file for d in self.decls})

    @property
    def names(self) -> list[str]:
        return sorted({d.name for d in self.decls})


def scan() -> tuple[list[Group], int]:
    files = _iter_files()
    decls: list[Decl] = []
    for p in files:
        rel = p.relative_to(_WORKSHOP).as_posix()
        src = p.read_text(errors="replace")
        code, nocom = _lex(src)
        decls.extend(_extract(code, nocom, rel))
    by_digest: dict[str, list[Decl]] = {}
    for d in decls:
        by_digest.setdefault(d.digest, []).append(d)
    groups = [
        Group(dig, sorted(ds, key=lambda d: (d.file, d.line)))
        for dig, ds in by_digest.items()
        if len({d.file for d in ds}) >= 2
    ]
    groups.sort(key=lambda g: (-len(g.files), g.names[0]))
    return groups, len(files)


def _changed_files(rev: str) -> set[str]:
    """Mirror reviewer.sh's CHANGED_ALL: tracked diff + staged diff + untracked."""
    out: set[str] = set()
    for cmd in (
        ["git", "diff", "--name-only", rev],
        ["git", "diff", "--cached", "--name-only", rev],
        ["git", "ls-files", "--others", "--exclude-standard"],
    ):
        try:
            res = subprocess.run(cmd, cwd=_WORKSHOP, capture_output=True,
                                 text=True, timeout=30)
        except (OSError, subprocess.SubprocessError):
            continue
        out.update(l.strip() for l in res.stdout.splitlines() if l.strip())
    return out


def _regressions(groups: list[Group], baseline: dict) -> list[tuple[Group, int]]:
    """(group, baselined file count) for every group that is new or has grown.
    A baselined count of 0 means the group is new."""
    pinned = baseline.get("groups", {})
    out = []
    for g in groups:
        was = pinned.get(g.digest, {}).get("files", 0)
        if len(g.files) > was:
            out.append((g, was))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--all", action="store_true",
                    help="print every duplicate group, not just the regressions")
    ap.add_argument("--baseline", default=str(_BASELINE_PATH))
    ap.add_argument("--write-baseline", action="store_true",
                    help="pin the current groups as the baseline and exit")
    ap.add_argument("--only-changed", metavar="REV", default=None,
                    help="only FAIL for groups declared in a file changed since "
                         "REV; still prints every regression found")
    args = ap.parse_args()

    groups, scanned = scan()
    baseline_path = Path(args.baseline)

    if args.write_baseline:
        pinned = {
            "note": "body-hash -> how many FILES declare it. A new hash, or a "
                    "pinned hash in more files, is a regression. See the "
                    "header of check_duplicate_helpers.py.",
            "groups": {
                g.digest: {"names": g.names, "files": len(g.files),
                           "where": [f"{d.file}:{d.line}" for d in g.decls]}
                for g in groups
            },
        }
        baseline_path.write_text(json.dumps(pinned, indent=2, sort_keys=True) + "\n")
        print(f"check_duplicate_helpers: wrote baseline to {baseline_path} "
              f"({len(groups)} duplicate group(s) from {scanned} file(s))")
        return 0

    try:
        baseline = json.loads(baseline_path.read_text())
    except (OSError, json.JSONDecodeError):
        baseline = {}

    regressions = _regressions(groups, baseline) if baseline else []
    if args.only_changed is not None:
        changed = _changed_files(args.only_changed)
        gating = [(g, w) for g, w in regressions if any(f in changed for f in g.files)]
    else:
        gating = regressions

    if args.json:
        def _g(g: Group, was: int | None = None) -> dict:
            d = {
                "digest": g.digest,
                "names": g.names,
                "files": g.files,
                "declarations": [{"name": x.name, "file": x.file, "line": x.line}
                                 for x in g.decls],
            }
            if was is not None:
                d["baseline_files"] = was
            return d
        print(json.dumps({
            "scanned_files": scanned,
            "duplicate_groups": [_g(g) for g in groups],
            "regressions": [_g(g, w) for g, w in regressions],
            "gating_regressions": [_g(g, w) for g, w in gating],
        }, indent=2, sort_keys=False))
        return 1 if gating else 0

    print(f"check_duplicate_helpers: {scanned} typescript file(s) scanned, "
          f"{len(groups)} helper body/bodies declared in more than one file")

    if not baseline:
        print(f"\n    no baseline at {baseline_path} -- run --write-baseline first")

    if args.all or not baseline:
        for g in groups:
            print(f"\n    {'/'.join(g.names)}  ({len(g.files)} files, body {g.digest})")
            for d in g.decls:
                print(f"        {d.name:20} {d.file}:{d.line}")

    if regressions:
        print(f"\n=== {len(regressions)} duplicated helper(s) NEW or GROWN since "
              f"the pinned baseline")
        for g, was in regressions:
            mark = " <- GATING (touches the current diff)" if (g, was) in gating else ""
            what = "new" if was == 0 else f"{was} -> {len(g.files)} files"
            print(f"    {'/'.join(g.names)}  ({what}){mark}")
            for d in g.decls:
                print(f"        {d.name:20} {d.file}:{d.line}")
            print(f"        body: {g.decls[0].body[:120]}"
                  f"{'...' if len(g.decls[0].body) > 120 else ''}")
        print("\ncheck_duplicate_helpers: move the helper to one module and import "
              "it. lib/time.ts, lib/bytes.ts and lib/sha.ts are where the pure "
              "formatters live; a helper local to one app belongs in a pure "
              "module inside that app's folder.")
        if args.only_changed is not None and not gating:
            print(f"\ncheck_duplicate_helpers: none of them touch a file changed "
                  f"since {args.only_changed}; not blocking this diff for debt it "
                  f"didn't introduce.")
    elif baseline:
        print("\ncheck_duplicate_helpers: no new duplicated helper against the "
              "pinned baseline")

    return 1 if gating else 0


if __name__ == "__main__":
    raise SystemExit(main())
