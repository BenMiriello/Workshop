#!/bin/bash
# auto_pr.sh — masini auto-PR for own bug fixes (task 5h.1)
#
# Usage:
#   auto_pr.sh --repo <path> --title <title> --body <body_text> [--diff <diff_text>] [--log-ref <ref>]
#
# Behavior:
#   - Default (MASINI_AUTO_PR unset or !=1): dry-run — writes PR body to
#     ~/workshop/.runtime/auto-prs/<ts>.md and prints the path.
#   - MASINI_AUTO_PR=1: real — runs `gh pr create` inside <repo>. Requires the
#     repo to have a GitHub remote and to be on a non-default branch.
#
# Gating switch lives in /home/clawd-a/.config/workshop/secrets.env:
#   MASINI_AUTO_PR=1

set -euo pipefail

SECRETS=/home/clawd-a/.config/workshop/secrets.env
AUTO_PRS_DIR=/home/clawd-a/workshop/.runtime/auto-prs

# Load secrets (sets MASINI_AUTO_PR if present)
[[ -r "$SECRETS" ]] && { set -a; . "$SECRETS"; set +a; }

MASINI_AUTO_PR="${MASINI_AUTO_PR:-0}"

REPO=""
TITLE=""
BODY=""
DIFF=""
LOG_REF=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --repo)    REPO="$2";    shift 2 ;;
    --title)   TITLE="$2";   shift 2 ;;
    --body)    BODY="$2";    shift 2 ;;
    --diff)    DIFF="$2";    shift 2 ;;
    --log-ref) LOG_REF="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 1 ;;
  esac
done

if [[ -z "$TITLE" || -z "$BODY" ]]; then
  echo "auto_pr.sh: --title and --body are required" >&2
  exit 1
fi

TS=$(date -u +%Y%m%dT%H%M%SZ)
SLUG=$(echo "$TITLE" | tr '[:upper:]' '[:lower:]' | tr -cs 'a-z0-9' '-' | head -c 40 | sed 's/-*$//')

mkdir -p "$AUTO_PRS_DIR"
PR_FILE="$AUTO_PRS_DIR/${TS}_${SLUG}.md"

# Build the markdown body stored in both dry-run and real modes
FULL_BODY="## Summary

${BODY}"

if [[ -n "$DIFF" ]]; then
  FULL_BODY="${FULL_BODY}

## Diff

\`\`\`diff
${DIFF}
\`\`\`"
fi

if [[ -n "$LOG_REF" ]]; then
  FULL_BODY="${FULL_BODY}

## Log reference

${LOG_REF}"
fi

FULL_BODY="${FULL_BODY}

---
_Auto-generated by masini cron agent (task 5h.1). Repo: ${REPO:-unspecified}. Mode: $([ "$MASINI_AUTO_PR" = "1" ] && echo real || echo dry-run)._"

# Always write the dry-run file (serves as the record even in real mode)
{
  echo "# PR: ${TITLE}"
  echo ""
  echo "$FULL_BODY"
} > "$PR_FILE"

if [[ "$MASINI_AUTO_PR" != "1" ]]; then
  echo "dry-run: PR body written to $PR_FILE"
  exit 0
fi

# Real mode: gh pr create inside the repo directory.
if [[ -z "$REPO" ]]; then
  echo "auto_pr.sh: --repo required in real mode" >&2
  exit 1
fi

if [[ ! -d "$REPO/.git" ]]; then
  echo "auto_pr.sh: $REPO is not a git repo" >&2
  exit 1
fi

CURRENT_BRANCH=$(git -C "$REPO" symbolic-ref --short HEAD 2>/dev/null || echo "")
DEFAULT_BRANCH=$(git -C "$REPO" symbolic-ref --short refs/remotes/origin/HEAD 2>/dev/null | sed 's|.*/||' || echo "main")

if [[ "$CURRENT_BRANCH" == "$DEFAULT_BRANCH" || -z "$CURRENT_BRANCH" ]]; then
  echo "auto_pr.sh: must be on a non-default branch to create a PR (currently: ${CURRENT_BRANCH:-detached})" >&2
  exit 1
fi

PR_URL=$(gh pr create --repo "$(git -C "$REPO" remote get-url origin)" \
  --title "$TITLE" \
  --body "$FULL_BODY" 2>&1)
echo "real mode: PR created: $PR_URL"
echo "  body also at: $PR_FILE"
